"""Generates src/domain/fodmara/foods.ts from scripts/i18n/foods.tsv (names go to the locales via build.py).
Run: python3 scripts/gen-foods.py  — never edit foods.ts by hand; keys are stable ids (never rename, only add)."""
import csv, os, json
ROOT = os.path.join(os.path.dirname(__file__), "..")
rows = list(csv.DictReader(open(os.path.join(ROOT, "scripts/i18n/foods.tsv")), delimiter="\t"))
keys = [r["key"] for r in rows]; assert len(keys) == len(set(keys)), "duplicate food key"
G = {"fructan", "gos", "lactose", "fructose", "sorbitol", "mannitol"}
out = ["// GENERATED by scripts/gen-foods.py from scripts/i18n/foods.tsv – do not edit.",
       "// Which FODMAP groups a food typically contains, from public dietary literature. No amounts, no traffic lights:",
       "// `portion` marks foods where the amount decides a lot (small servings often fine). Labels: t(`food.items.<key>`).",
       'import type { FodmapGroup, FoodCat } from "./fodmap";', "",
       "export type CatalogFood = { key: string; cat: FoodCat; groups: FodmapGroup[]; portion: boolean };",
       "export const FOODS: CatalogFood[] = ["]
for r in rows:
    gs = [g for g in r["groups"].split(",") if g]
    assert all(g in G for g in gs), r
    out.append(f'  {{ key: "{r["key"]}", cat: "{r["cat"]}", groups: {json.dumps(gs)}, portion: {"true" if r["portion"] == "p" else "false"} }},')
out += ["];", "export const FOOD_BY_KEY = new Map(FOODS.map((f) => [f.key, f]));", ""]
open(os.path.join(ROOT, "src/domain/fodmara/foods.ts"), "w").write("\n".join(out))
print(len(rows), "foods")
